-- Онлайн-бриф: публичная форма должна называть АГЕНТСТВО, а не сервис.
--
-- Проблема (найдена 2026-08-03). Страница ?brief=<agency> рисует в шапке жёстко
-- зашитые логотип и подпись «ADERVIS · Видеопродакшн». Для самого владельца это
-- незаметно — он и есть ADERVIS. Но для любой другой студии это значит, что её
-- заказчик открывает форму и видит, что бриф собирает ADERVIS: чужая компания,
-- к тому же прямой конкурент по видеопродакшну.
--
-- Портал КП этот случай решает правильно: контент агентства сверху, маленькая
-- подпись «Сделано в ADERVIS» внизу (и та снимается на платном тарифе). Бриф
-- остался единственным местом, где сервис представляется отправителем.
--
-- Имя и логотип агентства лежат в agency_state.state_json -> 'company', а он
-- закрыт RLS (только владелец). Публичная форма анонимна, поэтому нужна такая же
-- узкая SECURITY DEFINER-функция, как get_brief_template: отдаёт ДВА поля и
-- ничего больше.
--
-- Приватность: раскрывается только то, что агентство и так печатает на своих
-- документах, и только тому, кто знает UUID из ссылки, которую агентство само
-- разослало. Ни контактов, ни сделок, ни сумм здесь нет.
-- ═══════════════════════════════════════════════════════════════════════

create or replace function public.get_brief_agency(p_agency_id text)
returns jsonb
language sql
security definer
set search_path = public
stable
as $$
  select jsonb_build_object(
    'name', coalesce(state_json -> 'company' ->> 'name', ''),
    'logo', coalesce(state_json -> 'company' ->> 'logoUrl', '')
  )
  from agency_state
  where id = p_agency_id
$$;

-- Публичная форма ходит под анонимным ключом.
revoke all on function public.get_brief_agency(text) from public;
grant execute on function public.get_brief_agency(text) to anon, authenticated;

