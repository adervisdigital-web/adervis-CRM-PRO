-- client_portals.project_id: UUID → text. Чинит «Создать КП» для ВСЕХ сделок.
--
-- Проблема (найдена 2026-08-03 по жалобе владельца «не работает кнопка Создать КП»,
-- на экране висел тост `invalid input syntax for type uuid: "proj_otask_18924"`).
--
-- Колонка заведена как UUID (20260704000002_client_portal_project_id.sql), но
-- идентификатор проекта UUID НИКОГДА не был:
--   uid("project") → «project_3431d8c5f47643828fd2c35a08876b25» (префикс + hex);
--   импорт из O!task → «proj_otask_18924».
-- Ни то, ни другое Postgres как uuid не принимает, поэтому INSERT в client_portals
-- падал целиком — то есть КП не создавалось ни для одной сделки. Сломано с
-- 04.07.2026, с коммита d35f294, которым колонку и добавили.
--
-- Почему не поймали раньше: тесты гоняются в local mode, где _supabase нет вовсе,
-- и до записи в базу дело не доходит. Проверять этот путь можно только живым
-- аккаунтом.
--
-- Побочно чинится и то, ради чего колонку заводили: calendar-feed?portal=<id>
-- сверяет project_id со списком savedProjects, где id — те же строки с префиксом.
-- Совпасть с uuid они не могли, поэтому фид дедлайна сделки для клиента всегда
-- был пуст.
--
-- Тип text, а не uuid с переписыванием идентификаторов: id проектов живут в
-- state_json агентства, в снапшотах, в задачах и в ссылках — менять их формат
-- задним числом означало бы миграцию всего состояния ради одной колонки.
--
-- Данных в колонке фактически нет (все INSERT с ней падали), поэтому USING
-- достаточно тривиального, и переписывать нечего.
-- ═══════════════════════════════════════════════════════════════════════

alter table public.client_portals
  alter column project_id type text using project_id::text;

-- Индекс под lookup «есть ли уже КП у этой сделки» (_findPortalForProject):
-- раньше он был бессмысленным, потому что совпадений не бывало в принципе.
create index if not exists client_portals_project_id_idx
  on public.client_portals (project_id);
