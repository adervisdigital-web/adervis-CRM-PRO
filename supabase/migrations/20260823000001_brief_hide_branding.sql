-- ═══════════════════════════════════════════════════════════════════════
-- Подпись «Powered by ADERVIS» на публичном брифе — снимать на платном тарифе.
--
-- Найдено 2026-08-23 при осмотре брифа глазами заказчика. На клиентском портале
-- КП подпись «Сделано в ADERVIS» снимается флагом hide_branding (миграция
-- 20260727000001), а на публичной форме брифа она стоит БЕЗУСЛОВНО: RPC
-- get_brief_agency (20260803000005) возвращает только name и logo, и флагу
-- просто неоткуда взяться.
--
-- Формально обещание нарушено не было: переключатель в настройках называется
-- «Подпись на клиентском КП» и говорит про КП. Но студия, оплатившая снятие
-- подписи, видела её на второй своей публичной странице — решение владельца
-- (2026-08-23): распространить флаг и на бриф.
--
-- ── Чем это отличается от КП ────────────────────────────────────────────
--
-- У КП флаг — СНИМОК: он пишется в client_portals в момент создания ссылки, и
-- уже разосланные КП не переписываются задним числом (условия сделки не должны
-- меняться после отправки). У брифа снимка нет и быть не может: это одна живая
-- ссылка студии, а не документ по конкретной сделке. Поэтому флаг считается
-- ЗДЕСЬ, на каждый запрос, и подпись исчезает/возвращается вместе с тарифом.
--
-- ── Почему проверка своя, а не _agency_write_allowed ────────────────────
--
-- Та функция (20260820000002) отвечает на другой вопрос — «можно ли писать» — и
-- пускает 'trial'. Здесь нужен ПЛАТНЫЙ тариф, ровно как isPaidPlan() в app.js:
-- status = 'active' и срок не истёк. Триал подпись убирать не даёт.
--
-- Приватность: наружу по-прежнему уходит только то, что агентство само печатает
-- на своих документах, плюс один boolean. Он косвенно говорит, что тариф
-- оплачен, — но это и так видно по отсутствию подписи на КП той же студии.
--
-- Тело функции скопировано из 20260803000005 и ДОПИСАНО, а не переписано по
-- памяти: 19.08 на переписывании такой же функции едва не потерялись белые
-- списки полей.
-- ═══════════════════════════════════════════════════════════════════════

create or replace function public.get_brief_agency(p_agency_id text)
returns jsonb
language sql
security definer
set search_path = public
stable
as $$
  select jsonb_build_object(
    'name', coalesce(a.state_json -> 'company' ->> 'name', ''),
    'logo', coalesce(a.state_json -> 'company' ->> 'logoUrl', ''),
    -- Сравнение jsonb, а не ::boolean: каст упал бы на любом неожиданном
    -- значении в состоянии, а функция обязана отдать форму даже тогда.
    'hide_branding', (
      coalesce(a.state_json -> 'company' -> 'hideProposalBranding' = 'true'::jsonb, false)
      and exists (
        select 1 from profiles p
        where p.id::text = p_agency_id
          and p.subscription_status = 'active'
          and (p.subscription_expires_at is null or p.subscription_expires_at > now())
      )
    )
  )
  from agency_state a
  where a.id = p_agency_id
$$;

-- Права — как были: публичная форма ходит под анонимным ключом.
-- Нужны ОБА revoke: public даёт право всем ролям скопом, anon — отдельно.
revoke all on function public.get_brief_agency(text) from public;
revoke all on function public.get_brief_agency(text) from anon;
grant execute on function public.get_brief_agency(text) to anon, authenticated;

